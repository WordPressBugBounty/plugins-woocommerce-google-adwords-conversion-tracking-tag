	/**
	 * POST /broker/meta/connect/start: begin the Meta connect (Facebook Login
	 * for Business). Mirrors the Google connect including the enroll-on-demand
	 * and single re-enroll retry on a stale site token.
	 */
	public function handle_meta_connect_start( $request ) {

		$params     = $request->get_json_params();
		$return_url = ( is_array($params) && isset($params['returnUrl']) ) ? esc_url_raw($params['returnUrl']) : '';

		if (!$return_url) {
			return new \WP_REST_Response(
				[
					'ok'      => false,
					'code'    => 'BAD_REQUEST',
					'message' => 'returnUrl is required.',
				],
				400
			);
		}

		if (!self::is_enrolled()) {
			$enroll = self::enroll();

			if (!$enroll['ok']) {
				return self::error_response($enroll);
			}
		}

		$result = self::broker_request('POST', '/v1/meta/connect/start', [ 'returnUrl' => $return_url ]);

		if (!$result['ok'] && 401 === $result['status']) {
			$enroll = self::enroll();

			if ($enroll['ok']) {
				$result = self::broker_request('POST', '/v1/meta/connect/start', [ 'returnUrl' => $return_url ]);
			}
		}

		if (!$result['ok']) {
			return self::error_response($result);
		}

		return new \WP_REST_Response($result['body'], 200);
	}

	/**
	 * POST /broker/meta/disconnect: revoke the Meta login and purge the
	 * broker-side token. Enrollment survives, like the Google disconnect.
	 */
	public function handle_meta_disconnect() {

		if (!self::is_enrolled()) {
