				'callback'            => [ $this, 'handle_meta_select' ],
				'permission_callback' => [ $this, 'can_current_user_edit_options' ],
			]);
		}
	}

	// ─── Enrollment state ───────────

	private static function get_state() {
		$state = get_option(self::OPTION_KEY);
		return is_array($state) ? $state : [];
	}

	private static function save_state( $state ) {
		update_option(self::OPTION_KEY, $state, false);
	}

	public static function is_enrolled() {
		$state = self::get_state();
		return !empty($state['site_token']);
	}

	/**
	 * The site base URL the broker enrolls: the frontend home URL, https,
	 * no trailing slash. Must match where /wp-json/pmw/v1/broker/challenge
	 * is publicly reachable.
	 *
	 * @return string
	 */
	private static function get_site_base_url() {
		return untrailingslashit(home_url());
	}

	// ─── Route handlers ───────────

	/**
	 * GET /broker/status: enrollment + per-provider readiness. Cheap local
	 * answer when not enrolled; otherwise proxied to the broker.
	 */
	public function handle_status() {

		if (!self::is_enrolled()) {
			return new \WP_REST_Response(
				[
					'ok'        => true,
					'enrolled'  => false,
					'connected' => false,
					'ga4'       => 'not_connected',
					'ads'       => 'not_connected',
				],
				200
			);
		}

		$result = self::broker_request('GET', '/v1/status');

		if (!$result['ok']) {
			return self::error_response($result);
		}

		$body             = $result['body'];
		$body['enrolled'] = true;

		return new \WP_REST_Response($body, 200);
	}

	/**
	 * POST /broker/connect/start: begin the Google connect. Enrolls the site
	 * first when needed (one button does both). Returns the redirect URL the
	 * browser must navigate to (top-level redirect, not a popup).
	 */
	public function handle_connect_start( $request ) {

		$params     = $request->get_json_params();
		$return_url = ( is_array($params) && isset($params['returnUrl']) ) ? esc_url_raw($params['returnUrl']) : '';

		if (!$return_url) {
			return new \WP_REST_Response(
				[
					'ok'      => false,
					'code'    => 'BAD_REQUEST',
					'message' => 'returnUrl is required.',
				],
				400
			);
		}

		if (!self::is_enrolled()) {
			$enroll = self::enroll();

			if (!$enroll['ok']) {
				return self::error_response($enroll);
			}
		}

		$result = self::broker_request('POST', '/v1/connect/start', [ 'returnUrl' => $return_url ]);

		// A stale or replaced token cannot start a connect. Re-enroll once
		// (re-proves site control, replaces the token) and retry.
		if (!$result['ok'] && 401 === $result['status']) {
			$enroll = self::enroll();

			if ($enroll['ok']) {
				$result = self::broker_request('POST', '/v1/connect/start', [ 'returnUrl' => $return_url ]);
			}
		}

		if (!$result['ok']) {
			return self::error_response($result);
		}

		return new \WP_REST_Response($result['body'], 200);
	}

	/**
	 * POST /broker/disconnect: revoke at Google and purge the broker-side
	 * credentials. The enrollment (site token) survives so reconnecting is
	 * one click.
	 */
	public function handle_disconnect() {

		if (!self::is_enrolled()) {
			return new \WP_REST_Response([ 'ok' => true ], 200);
		}

		$result = self::broker_request('POST', '/v1/disconnect');

		if (!$result['ok']) {
			return self::error_response($result);
		}

		return new \WP_REST_Response($result['body'], 200);
	}

	public function handle_ads_customers() {
