	public function handle_meta_select( $request ) {
		return self::proxy('POST', '/v1/meta/select', self::pick_params($request, [ 'pixelId' ]));
	}

	// ─── Enrollment ───────────

	/**
	 * Run the challenge enrollment: begin -> publish challenge -> complete.
	 * Returns a broker_request-shaped array.
	 *
	 * @return array
	 */
	private static function enroll() {

		$begin = self::broker_request(
			'POST',
			'/v1/enroll/begin',
			[ 'siteUrl' => self::get_site_base_url() ],
			false
		);

		if (!$begin['ok']) {
			return $begin;
		}

		$body          = $begin['body'];
		$enrollment_id = isset($body['enrollmentId']) ? $body['enrollmentId'] : '';
		$challenge     = isset($body['challenge']) ? $body['challenge'] : '';

		if (!$enrollment_id || !$challenge) {
			return [
				'ok'        => false,
				'status'    => 502,
				'body'      => [
					'ok'      => false,
					'code'    => 'UPSTREAM_ERROR',
					'message' => 'The broker returned an incomplete enrollment.',
				],
				'requestId' => $begin['requestId'],
			];
		}

		// Publish the challenge, then have the broker verify it. The public
		// challenge route reads this transient.
		set_transient(self::CHALLENGE_TRANSIENT, $challenge, 10 * MINUTE_IN_SECONDS);

		$complete = self::broker_request(
			'POST',
			'/v1/enroll/complete',
			[
				'enrollmentId' => $enrollment_id,
				'distro'       => defined('PMW_DISTRO') ? PMW_DISTRO : '',
				'version'      => defined('PMW_CURRENT_VERSION') ? PMW_CURRENT_VERSION : '',
			],
			false
		);

		delete_transient(self::CHALLENGE_TRANSIENT);

		if (!$complete['ok']) {
			return $complete;
		}

		$body = $complete['body'];

		if (empty($body['siteId']) || empty($body['siteToken'])) {
			return [
				'ok'        => false,
				'status'    => 502,
				'body'      => [
					'ok'      => false,
					'code'    => 'UPSTREAM_ERROR',
					'message' => 'The broker returned an incomplete enrollment token.',
				],
				'requestId' => $complete['requestId'],
			];
		}

		self::save_state([
			'site_id'     => $body['siteId'],
			'site_token'  => $body['siteToken'],
			'enrolled_at' => time(),
		]);

		return $complete;
	}

	// ─── Broker HTTP plumbing ───────────

	/**
	 * Whitelist JSON params from the REST request body.
	 *
	 * @param \WP_REST_Request $request
	 * @param array            $keys
	 * @return array
	 */
	private static function pick_params( $request, $keys ) {

		$params = $request->get_json_params();
		$out    = [];

		if (!is_array($params)) {
			return $out;
		}

		foreach ($keys as $key) {
			if (isset($params[$key]) && is_string($params[$key])) {
				$out[$key] = $params[$key];
			}
		}

		return $out;
	}

	/**
	 * Authenticated proxy: run the broker request and map it 1:1 into the
	 * REST response (body, status and the broker's X-Request-Id).
	 *
	 * @param string     $method
	 * @param string     $path
	 * @param array|null $body
	 * @return \WP_REST_Response
	 */
	private static function proxy( $method, $path, $body = null ) {

		$result = self::broker_request($method, $path, $body);

		if (!$result['ok']) {
			return self::error_response($result);
		}

		return new \WP_REST_Response($result['body'], 200);
	}

	/**
	 * One HTTP call to the broker.
	 *
	 * @param string     $method    GET|POST
	 * @param string     $path      e.g. /v1/status
	 * @param array|null $body      JSON body for POSTs.
	 * @param bool       $with_auth Attach the per-site bearer token.
	 * @return array {
	 *     ok:        bool  True on HTTP 2xx with ok!==false.
	 *     status:    int   HTTP status (0 on network error).
	 *     body:      array Decoded JSON body (with code/message on errors).
	 *     requestId: string|null The broker's X-Request-Id for support lookups.
	 * }
	 */
	private static function broker_request( $method, $path, $body = null, $with_auth = true, $extra_headers = [] ) {

		$headers = [
			'Accept'        => 'application/json',
			'X-PMW-Version' => defined('PMW_CURRENT_VERSION') ? PMW_CURRENT_VERSION : '',
		];

		if ($with_auth) {
			$state = self::get_state();

			if (empty($state['site_token'])) {
				return [
					'ok'        => false,
					'status'    => 409,
					'body'      => [
						'ok'      => false,
						'code'    => 'NOT_ENROLLED',
						'message' => 'This site is not enrolled with the connection service yet.',
					],
					'requestId' => null,
				];
			}

			$headers['Authorization'] = 'Bearer ' . $state['site_token'];

			if (!empty($state['site_id'])) {
				$headers['X-PMW-Site'] = $state['site_id'];
			}
		}

		$args = [
			'method'  => $method,
			'timeout' => 20,
			'headers' => array_merge($headers, (array) $extra_headers),
		];

		// Always JSON-typed, even on body-less POSTs (disconnect): the broker's
		// Astro CSRF check rejects untyped POSTs as cross-site form submissions.
		if ('GET' !== $method) {
			$args['headers']['Content-Type'] = 'application/json';
			$args['body']                    = wp_json_encode(is_null($body) ? new \stdClass() : $body);
		}

		/**
		 * Some optimization and security plugins clamp EVERY outbound request
		 * to the WordPress default of 5 seconds through the http_request_args
		 * filter, which overrides the explicit timeout above. Seen live: a
		 * Data Manager relay that the broker completed in 11.6 seconds died
		 * shop-side with "cURL error 28: Operation timed out after 5002
		 * milliseconds". Re-assert the timeout after all other filters, for
		 * this one request only.
		 */
		$broker_url      = self::get_broker_url();
		$enforce_timeout = static function ( $parsed_args, $url ) use ( $broker_url ) {
			if (is_string($url) && 0 === strpos($url, $broker_url)) {
				$parsed_args['timeout'] = 20;
			}
			return $parsed_args;
		};

		add_filter('http_request_args', $enforce_timeout, PHP_INT_MAX, 2);

		$response = wp_remote_request($broker_url . $path, $args);

		remove_filter('http_request_args', $enforce_timeout, PHP_INT_MAX);

		if (is_wp_error($response)) {
			return [
				'ok'        => false,
				'status'    => 0,
				'body'      => [
					'ok'      => false,
					'code'    => 'NETWORK_ERROR',
					'message' => 'Could not reach the connection service: ' . $response->get_error_message(),
				],
				'requestId' => null,
			];
		}

		$status     = (int) wp_remote_retrieve_response_code($response);
		$request_id = wp_remote_retrieve_header($response, 'x-request-id');
		$decoded    = json_decode(wp_remote_retrieve_body($response), true);

		if (!is_array($decoded)) {
			$decoded = [
				'ok'      => false,
				'code'    => 'UPSTREAM_ERROR',
				'message' => 'The connection service returned an unexpected response (' . $status . ').',
			];
		}

		$ok = $status >= 200 && $status < 300 && ( !isset($decoded['ok']) || false !== $decoded['ok'] );

		return [
			'ok'        => $ok,
			'status'    => $status,
			'body'      => $decoded,
			'requestId' => is_string($request_id) && '' !== $request_id ? $request_id : null,
		];
	}

	/**
	 * Map a failed broker_request into the REST response. The broker's
	 * request id rides along so support tickets carry the exact log key.
	 *
	 * @param array $result
	 * @return \WP_REST_Response
	 */
	private static function error_response( $result ) {

		$body = $result['body'];

		if ($result['requestId']) {
			$body['requestId'] = $result['requestId'];
		}

		$status = $result['status'] >= 400 ? $result['status'] : 502;

		return new \WP_REST_Response($body, $status);
	}
