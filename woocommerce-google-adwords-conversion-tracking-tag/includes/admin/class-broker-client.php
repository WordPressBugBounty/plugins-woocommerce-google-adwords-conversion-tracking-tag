	/**
	 * POST /broker/ga4/properties: create a GA4 property (the account-has-no-
	 * properties onboarding path). The shop's locale details are injected
	 * server-side so the wizard needs no timezone/currency inputs.
	 */
	public function handle_ga4_properties_create( $request ) {

		$params = self::pick_params($request, [ 'account', 'displayName' ]);

		if (empty($params['displayName'])) {
			$params['displayName'] = get_bloginfo('name');
		}

		// GA4 requires an IANA zone; WP offset-style settings ("+02:00") cannot
		// be mapped cleanly, so those fall back to UTC.
		$timezone = function_exists('wp_timezone_string') ? wp_timezone_string() : '';

		if (!$timezone || preg_match('/^[+-]/', $timezone)) {
			$timezone = 'UTC';
		}

		$params['timeZone']     = $timezone;
		$params['currencyCode'] = function_exists('get_woocommerce_currency') ? get_woocommerce_currency() : 'USD';

		return self::proxy('POST', '/v1/ga4/properties', $params);
	}

