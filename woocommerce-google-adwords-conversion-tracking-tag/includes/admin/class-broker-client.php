/**
 * Client for the PMW connection broker (https://pmw.sweetcode.com).
 *
 * The broker lets a shop manager connect their Google account once and then
 * pick or create a Google Ads purchase conversion action (and a GA4 web data
 * stream) without copy-pasting IDs. The merchant's Google refresh token is
 * stored encrypted on the broker and never reaches this site; this class only
 * holds the per-site bearer token issued during enrollment.
 *
 * EXPERIMENTAL: every route registers only while Helpers::is_experiment() is
 * true (EXPERIMENTAL_PMW / PMW_EXPERIMENTS in wp-config.php). Not part of the
 * public feature set until Google approves the OAuth consent screen for a
 * public audience. The manual conversion ID and label fields remain the
 * primary path and always win.
 *
 * Flow (see pmw-web docs/oauth-broker-design.md):
 *  1. enroll: the broker issues a challenge, this site serves it on a public
 *     endpoint, the broker verifies it and issues the per-site token.
 *  2. connect: browser redirect to the broker -> Google consent -> back to
 *     wp-admin with pmw_connected=1 or pmw_connect_error=<code>.
 *  3. configure: authenticated proxy calls to list/create conversion actions
 *     and data streams; the resulting IDs are saved through the normal
 *     settings pipeline.
 *
 * @since 1.63.0
 */
class Broker_Client {

	private static $instance;

	protected static $rest_namespace = 'pmw/v1';

	/**
	 * Option holding the broker enrollment state:
	 * [ 'site_id' => string, 'site_token' => string, 'enrolled_at' => int ]
	 * Not autoloaded; the token is only needed on broker proxy calls.
	 */
	const OPTION_KEY = 'pmw_broker';

	/** Transient holding the broker-issued enrollment challenge (10 min). */
	const CHALLENGE_TRANSIENT = 'pmw_broker_challenge';

	public static function get_instance() {
		if (is_null(self::$instance)) {
			self::$instance = new self();
		}
		return self::$instance;
	}

	public function __construct() {
		add_action('rest_api_init', [ $this, 'register_routes' ]);
	}

	/**
	 * The broker base URL.
	 *
	 * @return string
	 */
	public static function get_broker_url() {

		/**
		 * Filters the broker base URL, so dev setups can point at a local broker.
		 *
		 * @param string $broker_url The broker base URL.
		 *
		 * @since 1.62.1
		 */
		return untrailingslashit(apply_filters('pmw_broker_url', 'https://pmw.sweetcode.com'));
	}

	// Extracted the code because the QIT semgrep rule was triggered
	public function can_current_user_edit_options() {
		return Environment::can_current_user_edit_options();
	}

	/**
	 * Permission callback for the public /broker/challenge endpoint.
	 *
	 * Public BY DESIGN (ACME http-01 style): the challenge is a broker-generated
	 * one-time value that only exists for the ~10 minutes of an enrollment
	 * started by an admin of this site, and reading it proves nothing.
	 * Named method instead of an inline closure because the QIT semgrep rule
	 * rest-route.permission-callback.return-true flags inline callbacks.
	 *
	 * @return bool
	 */
	public function is_challenge_endpoint_public() {
		return true;
	}

	public function register_routes() {

		// Experimental feature flag: without it the broker endpoints do not exist.
		if (!Helpers::is_experiment()) {
			return;
		}

		/**
		 * Public enrollment challenge endpoint. Public BY DESIGN: the value is
		 * generated by the broker for one specific enrollment attempt, so
		 * reading it proves nothing (ACME http-01 style). It exists only for
		 * the ~10 minutes of an enrollment started by an admin of this site.
		 */
		register_rest_route(self::$rest_namespace, '/broker/challenge', [
			'methods'             => \WP_REST_Server::READABLE,
			'callback'            => function () {

				$challenge = get_transient(self::CHALLENGE_TRANSIENT);

				if (!$challenge) {
					return new \WP_REST_Response([ 'challenge' => null ], 404);
				}

				return new \WP_REST_Response([ 'challenge' => $challenge ], 200);
			},
			'permission_callback' => [ $this, 'is_challenge_endpoint_public' ],
		]);

		// All routes below are admin-only proxies to the broker.

		register_rest_route(self::$rest_namespace, '/broker/status', [
			'methods'             => \WP_REST_Server::READABLE,
			'callback'            => [ $this, 'handle_status' ],
			'permission_callback' => [ $this, 'can_current_user_edit_options' ],
		]);

		register_rest_route(self::$rest_namespace, '/broker/connect/start', [
			'methods'             => \WP_REST_Server::CREATABLE,
			'callback'            => [ $this, 'handle_connect_start' ],
			'permission_callback' => [ $this, 'can_current_user_edit_options' ],
		]);

		register_rest_route(self::$rest_namespace, '/broker/disconnect', [
			'methods'             => \WP_REST_Server::CREATABLE,
			'callback'            => [ $this, 'handle_disconnect' ],
			'permission_callback' => [ $this, 'can_current_user_edit_options' ],
		]);

		register_rest_route(self::$rest_namespace, '/broker/ads/customers', [
			'methods'             => \WP_REST_Server::READABLE,
			'callback'            => [ $this, 'handle_ads_customers' ],
			'permission_callback' => [ $this, 'can_current_user_edit_options' ],
		]);

		register_rest_route(self::$rest_namespace, '/broker/ads/customers/(?P<cid>\d+)/conversions', [
			'methods'             => \WP_REST_Server::READABLE,
			'callback'            => [ $this, 'handle_ads_conversions_list' ],
			'permission_callback' => [ $this, 'can_current_user_edit_options' ],
		]);

		register_rest_route(self::$rest_namespace, '/broker/ads/conversions', [
			'methods'             => \WP_REST_Server::CREATABLE,
			'callback'            => [ $this, 'handle_ads_conversions_create' ],
			'permission_callback' => [ $this, 'can_current_user_edit_options' ],
		]);

